"""Argon draws the pitch's architecture diagram in Google's own render, watch, critique, fix loop.

    GOOGLE_API_KEY=... .venv/bin/python loop/diagram.py [--rounds 4] [--target 9]

Round 1: Argon writes a self-contained SVG. Every round: Chromium renders it to a PNG, Argon looks at the PNG (and the
source), scores it 1 to 10, lists issues and returns a fixed SVG. Stops at the target score or after the last round.
Output: runs/diagram/roundN/{diagram.svg,diagram.png,critique.json,fixed.svg}, runs/diagram/{diagram.svg,diagram.png,summary.json}.
"""
import argparse, json, pathlib, re, shutil, subprocess, sys, time
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from kit import ROOT, argon, client, cost, image_part, node_env, save_interaction, usage

OUT = ROOT / "runs" / "diagram"
RENDER = OUT / "render.mjs"

GOAL = """\
The diagram is for a hackathon pitch (Gemini 4 Argon hackathon, project "Did it learn?"). A judge has about ten seconds
with it, so it must read left to right at a glance: what goes in, what each stage does, what comes out. It shows the
pipeline that tells whether an AI build loop really learned a task or just learned the test.

The pipeline, in order:
1. Google's loop (render, watch, critique, fix) runs in a Managed Agents sandbox on 16 practice flights of a quadcopter
   course, and produces a controller (code) and a record (the full transcript).
2. Argon compresses the record into a 32-token recipe.
3. Fresh Managed Agents sandboxes rebuild a controller from the recipe alone (8 to 16 rebuilds per recipe).
4. Our code judge flies everything (the loop's controller and every rebuild) on 64 secret held-out flights.
5. Argon checks the agents' code two ways: a long-context read (944,000 tokens of transcripts in one request) and a
   long-output audit (every line of every controller annotated in one answer).
6. Argon watches flight video and calls each flight pass or fail.
7. At the table, Argon checks a live flight.

Two key results must appear on the diagram, as callouts, with these exact numbers:
- The cheater: 16/16 practice, then 0/64 held-out.
- The cheater's recipe passed the seed hunt to 8 of 8 rebuilds; the honest recipe, 0 of 8.
"""

RULES = """\
Hard constraints on the SVG:
- Root tag exactly: <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 560" width="1200" height="560">.
- Self-contained: no <script>, <style>, <image>, <foreignObject>, <a>, no external fonts, no URLs of any kind.
- Light background: first element a full-size rect filled with a near-white colour. Dark text on light shapes.
- Fonts via the attribute font-family="system-ui, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif" on the
  root or on groups. Body labels font-size 14 or larger; nothing under 13. Titles larger.
- Use presentation attributes (fill, stroke, font-size, text-anchor), never a <style> block or class names.
- All text in <text> elements; break long labels into several <text> lines (about 18 px apart). Keep each label
  short. A character at font-size 14 is about 7.5 px wide: size every box so its text fits with margin, and make
  sure no text overlaps another text, a box edge or an arrow.
- Arrows: use a single <marker> arrowhead defined in <defs> and reuse it. Arrows must not cross text.
- Plain words. No em dashes (U+2014), no en dashes (U+2013), no double hyphens: use commas or colons instead.
- No credit, byline, or signature of any kind on the drawing (no "drawn by", no model or company name as author).
  The words Argon and Managed Agents appear only as labels for the stages that use them.
- Numbers exactly as given in the goal, including "944,000", "16/16", "0/64", "8 of 8", "0 of 8", "32-token", "64 secret
  held-out flights", "16 practice flights".
Return the complete SVG document as one string.
"""

DRAW_SCHEMA = {"type": "object", "properties": {"notes": {"type": "string"}, "svg": {"type": "string"}}, "required": ["notes", "svg"]}
CRIT_SCHEMA = {"type": "object", "properties": {"score": {"type": "integer"}, "issues": {"type": "array", "items": {"type": "string"}},
                                                 "svg": {"type": "string"}}, "required": ["score", "issues", "svg"]}

REQUIRED = ["16/16", "0/64", "8 of 8", "0 of 8", "32-token", "944,000", "64", "16 practice"]
FORBIDDEN = ["<script", "<style", "<image", "<foreignObject", "<a ", "http:", "https:", "@import"]
CREDIT = re.compile(r"drawn by|built by|generated by|made by|created by|claude|codex|openai|anthropic|gpt", re.I)


def clean_svg(s):
    s = s.strip()
    s = re.sub(r"^```(?:svg|xml)?\s*", "", s)
    s = re.sub(r"\s*```$", "", s)
    i = s.find("<svg")
    return s[i:] if i >= 0 else s


def code_check(svg):
    """Checks a program can make; anything here goes back to Argon as a must-fix and blocks 'done'."""
    issues = []
    if "—" in svg or "–" in svg:
        issues.append("contains an em dash or en dash (U+2014 or U+2013); replace with a comma or colon")
    if re.search(r"\w--\w|\s--\s", svg):
        issues.append("contains a double hyphen used as punctuation")
    body = re.sub(r'xmlns(:\w+)?="[^"]*"', "", svg)  # the namespace declaration is the one URL allowed
    for f in FORBIDDEN:
        if f.lower() in body.lower():
            issues.append(f"contains forbidden content: {f}")
    if re.search(r"url\(\s*['\"]?\s*[^#'\")\s]", body):  # url(#id) for markers and gradients is fine; anything external is not
        issues.append("contains a url() that is not a local #fragment reference")
    if 'viewBox="0 0 1200 560"' not in svg:
        issues.append('root <svg> must have viewBox="0 0 1200 560"')
    for r in REQUIRED:
        if r not in svg:
            issues.append(f'missing required text or number: "{r}"')
    texts = " ".join(re.findall(r"<text[^>]*>(.*?)</text>", svg, flags=re.S))
    m = CREDIT.search(texts)
    if m:
        issues.append(f'credit or author text is not allowed on the drawing: "{m.group(0)}"')
    small = [float(x) for x in re.findall(r'font-size="([\d.]+)', svg)]
    small += [float(x) for x in re.findall(r"font-size:\s*([\d.]+)", svg)]
    if any(x < 13 for x in small):
        issues.append(f"font-size below 13 px found ({min(small):g}); make every label at least 13, body labels 14 or more")
    return issues


def render(svg_path, png_path):
    r = subprocess.run(["node", str(RENDER), str(svg_path), str(png_path)], cwd=ROOT, env=node_env(), capture_output=True, text=True, timeout=120)
    if r.returncode != 0:
        raise RuntimeError(f"render failed: {r.stderr[-1200:]}")


def draw(c):
    prompt = ("You are drawing an architecture diagram as SVG.\n\n" + GOAL + "\nDesign guidance: one clear left-to-right flow, "
              "numbered stages, a visibly distinct band or shading for the parts that run inside Managed Agents sandboxes, "
              "another for the checks Argon itself does, and the two results as callouts whose numbers are the largest text on "
              "the drawing after the title. Leave white space. A reader should see: build, compress, rebuild, judge on secret "
              "flights, and Argon reading, auditing, watching, checking live.\n\n" + RULES +
              "\nIn notes, say in two sentences how the layout is organised.")
    return argon(c, [{"type": "text", "text": prompt}], thinking="high", schema=DRAW_SCHEMA)


def critique(c, png, svg, code_issues):
    prompt = ("You are the critic in a render, watch, critique, fix loop. Attached is the rendered PNG of the current SVG "
              "diagram, and below it the SVG source.\n\n" + GOAL +
              "\nLook at the picture first, as a hackathon judge seeing it for ten seconds. Score it 1 to 10 for how well it "
              "serves that judge: 9 means a designer would ship it as is, 10 means nothing could be improved. Be strict and "
              "specific. Check in this order: (1) any text overlapping other text, boxes, or arrows, or clipped at an edge; "
              "(2) any text too small or too crowded to read; (3) are all seven stages and both results present with the exact "
              "numbers; (4) does the flow read left to right without ambiguity (arrow direction, grouping, numbering); "
              "(5) wasted or cramped space, uneven margins, inconsistent spacing; (6) any dash used as punctuation, any credit "
              "or author text. List every issue you see in `issues`, each one concrete (what, where). Then return in `svg` a "
              "complete fixed SVG that resolves every issue while keeping what works. If the score is 9 or 10 and nothing needs "
              "fixing, return the SVG unchanged.\n\n" + RULES +
              ("\nAutomated checks that FAILED on this SVG, each must be fixed:\n- " + "\n- ".join(code_issues) + "\n" if code_issues else "") +
              "\n\nCurrent SVG source:\n" + svg)
    return argon(c, [{"type": "text", "text": prompt}, image_part(png)], thinking="high", schema=CRIT_SCHEMA)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rounds", type=int, default=4)
    ap.add_argument("--target", type=int, default=9)
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    c = client()
    rounds, total = [], 0.0
    t0 = time.time()

    it = draw(c)
    rec = save_interaction(OUT / "round1" / "draw.json", it)
    total += rec["cost_usd"]
    svg = clean_svg(json.loads(it.output_text)["svg"])
    print(f"draw: ${rec['cost_usd']} {usage(it).get('total_output_tokens')} out tokens; notes: {json.loads(it.output_text)['notes'][:200]}")

    done, final = False, None
    for n in range(1, a.rounds + 1):
        rd = OUT / f"round{n}"
        rd.mkdir(exist_ok=True)
        (rd / "diagram.svg").write_text(svg)
        render(rd / "diagram.svg", rd / "diagram.png")
        code_issues = code_check(svg)
        it = critique(c, rd / "diagram.png", svg, code_issues)
        try:
            res = json.loads(it.output_text)
        except Exception:
            res = {"score": 0, "issues": ["critic returned no JSON"], "svg": svg}
        rec = save_interaction(rd / "critique.json", it, {"score": res["score"], "issues": res["issues"], "code_issues": code_issues})
        total += rec["cost_usd"]
        fixed = clean_svg(res.get("svg") or svg)
        (rd / "fixed.svg").write_text(fixed)
        rounds.append({"round": n, "score": res["score"], "issues": res["issues"], "code_issues": code_issues,
                       "cost_usd": rec["cost_usd"], "svg": str(rd / "diagram.svg"), "png": str(rd / "diagram.png")})
        print(f"round {n}: score {res['score']}, {len(res['issues'])} issues, {len(code_issues)} code issues, ${rec['cost_usd']}; total ${total:.3f}")
        for i in res["issues"] + code_issues:
            print("   -", i[:160])
        if res["score"] >= a.target and not code_issues:
            done, final = True, n
            break
        svg = fixed

    summary = {"rounds": rounds, "rounds_run": len(rounds), "reached_target": done, "target": a.target,
               "total_cost_usd": round(total, 4), "minutes": round((time.time() - t0) / 60, 1), "model": "gemini-4-argon"}
    finalize(summary, final)


def finalize(summary, final=None):
    """The final drawing. Target reached in round n: that round's drawing (Argon returned it unchanged). Otherwise the last
    round's fix: the loop ends with a fix, like Google's, so its product is the drawing after the last fix; it is rendered
    here but not scored by Argon (the scores in summary are for the draft each round started from)."""
    n = summary["rounds_run"]
    if final is not None:
        src, scored = OUT / f"round{final}" / "diagram.svg", True
    else:
        final, src, scored = n, OUT / f"round{n}" / "fixed.svg", False
    shutil.copy(src, OUT / "diagram.svg")
    render(OUT / "diagram.svg", OUT / "diagram.png")
    summary.update({"final_round": final, "final_from": str(src.relative_to(OUT)), "final_scored_by_argon": scored,
                    "final_code_issues": code_check((OUT / "diagram.svg").read_text()),
                    "final_svg": str(OUT / "diagram.svg"), "final_png": str(OUT / "diagram.png")})
    (OUT / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps({k: v for k, v in summary.items() if k != "rounds"}, indent=1))
    print("scores:", [r["score"] for r in summary["rounds"]])


if __name__ == "__main__":
    if "--finalize-only" in sys.argv:  # redo the final from the saved rounds; no model call
        S = json.loads((OUT / "summary.json").read_text())
        finalize(S, S["rounds_run"] if S["reached_target"] else None)
    else:
        main()
